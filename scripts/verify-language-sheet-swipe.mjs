import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const sheet=readFileSync('src/components/LanguageSelector.jsx','utf8');
assert.ok(sheet.includes("sheetRef=useRef(null)"));
assert.ok(sheet.includes("listRef=useRef(null)"));
assert.ok(sheet.includes("element.addEventListener('touchmove',move,{passive:false})"),'Android touchmove must be non-passive');
assert.ok(sheet.includes("element.addEventListener('touchend',finish,{passive:true})"),'The drawer should finish swipe on touchend');
assert.ok(sheet.includes("distance>=90||(distance>=36&&speed>0.65)"),'The drawer must recognize long and fast downward drags');
assert.ok(sheet.includes('gesture.fromList&&listRef.current?.scrollTop>1'),'Do not intercept the scrollable options list');
assert.ok(sheet.includes("if(deltaY<=0)"),'Upward swipes must not dismiss the drawer');
assert.ok(sheet.includes("target.closest('input,textarea,select')"),'Search field must retain normal keyboard interaction');
assert.ok(sheet.includes('data-language-options'),'The list needs its own scroll target');
assert.ok(sheet.includes('ref={sheetRef}'),'Touch gestures should cover the whole bottom sheet');
assert.ok(sheet.includes('ref={listRef}'),'Option scrolling needs a ref');
assert.ok(sheet.includes('element.removeEventListener(\'touchmove\',move)'),'Gesture listeners must be removed');
console.log('Language/Currency bottom-sheet swipe QA: touch-drag dismissal, keyboard and scroll preservation passed.');
